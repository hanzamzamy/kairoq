// Build-time tool: write a C++ source embedding files as byte arrays.
// Usage: embed <output.cpp> <name> <base dir> <file>...
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <iterator>
#include <string>
#include <vector>

int main(int argc, char** argv) {
    if (argc < 4) {
        std::fprintf(stderr, "usage: embed <output.cpp> <name> <base dir> <file>...\n");
        return 2;
    }
    const std::string name = argv[2];
    const std::filesystem::path base(argv[3]);
    std::string out = "// Generated by cmake/embed.cpp. Do not edit.\n#include \"kairoq/embedded.hpp\"\n\nnamespace kairoq {\nnamespace {\n";
    std::string table;
    char buf[8];
    for (int i = 4; i < argc; ++i) {
        std::ifstream in(argv[i], std::ios::binary);
        if (!in) {
            std::fprintf(stderr, "embed: cannot read %s\n", argv[i]);
            return 1;
        }
        const std::vector<unsigned char> data((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
        const std::string key = std::filesystem::relative(argv[i], base).generic_string();
        out += "const unsigned char data_" + std::to_string(i) + "[] = {";
        for (std::size_t k = 0; k < data.size(); ++k) {
            if (k % 24 == 0) out += "\n";
            std::snprintf(buf, sizeof buf, "%u,", data[k]);
            out += buf;
        }
        out += "0};\n";
        table += "    {\"" + key + "\", data_" + std::to_string(i) + ", " + std::to_string(data.size()) + "},\n";
    }
    out += "}  // namespace\n\nconst EmbeddedFile " + name + "[] = {\n" + table + "};\nconst std::size_t " + name + "_count = " +
           std::to_string(argc - 4) + ";\n\n}  // namespace kairoq\n";
    std::ofstream f(argv[1], std::ios::binary);
    f << out;
    return f ? 0 : 1;
}
