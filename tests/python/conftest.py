"""Test configuration and the validation report.

Tests record compared quantities with the ``validation`` fixture. At the end of the
session the records are written as a Markdown table and as JSON to the directory
named by KAIROQ_VALIDATION_DIR (default: build/validation).
"""

from __future__ import annotations

import datetime
import json
import os
import platform
import shutil
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
TESTDATA = ROOT / "testdata"

try:
    import kairoq  # noqa: F401  installed package
except ImportError:
    sys.path.insert(0, str(ROOT / "build" / "src" / "python"))
    import kairoq  # noqa: F401


def cli_path() -> str | None:
    env = os.environ.get("KAIROQ_CLI")
    if env:
        return env
    built = ROOT / "build" / "src" / "cli" / "kairoq"
    if built.exists():
        return str(built)
    return shutil.which("kairoq")


_records: list[dict] = []


class Validation:
    """Records a computed quantity against its reference and asserts the tolerance."""

    def __init__(self, test: str):
        self.test = test

    def check(self, case: str, quantity: str, value: float, reference: float, *, rel: float | None = None,
              abs_: float | None = None, unit: str = "", source: str = ""):
        err = value - reference
        rel_err = abs(err) / abs(reference) if reference else 0.0
        ok = (rel is not None and reference != 0 and rel_err <= rel) or (abs_ is not None and abs(err) <= abs_)
        _records.append({
            "test": self.test, "case": case, "quantity": quantity, "value": value, "reference": reference,
            "error": err, "relative_error": rel_err, "tolerance": f"rel {rel:g}" if rel is not None else f"abs {abs_:g}",
            "unit": unit, "source": source, "passed": bool(ok),
        })
        assert ok, f"{case}: {quantity} = {value} {unit}, reference {reference} (error {err:.3g}, relative {rel_err:.3g})"


@pytest.fixture
def validation(request) -> Validation:
    return Validation(request.node.nodeid)


def rel_text(r: dict) -> str:
    return "–" if r["reference"] == 0 else f"{r['relative_error']:.2e}"


def pytest_sessionfinish(session, exitstatus):
    if not _records:
        return
    out = Path(os.environ.get("KAIROQ_VALIDATION_DIR", ROOT / "build" / "validation"))
    out.mkdir(parents=True, exist_ok=True)
    meta = {
        "date": datetime.datetime.now().isoformat(timespec="seconds"),
        "python": platform.python_version(),
        "platform": platform.platform(),
    }
    (out / "report.json").write_text(json.dumps({"meta": meta, "records": _records}, indent=1))
    lines = [
        "# Validation report",
        "",
        f"Generated by the test suite on {meta['date']} ({meta['platform']}).",
        "",
        "| case | quantity | value | reference | relative error | tolerance | result |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for r in _records:
        lines.append(
            f"| {r['case']} | {r['quantity']} | {r['value']:.6g} {r['unit']} | {r['reference']:.6g} {r['unit']} | "
            f"{rel_text(r)} | {r['tolerance']} | {'pass' if r['passed'] else 'FAIL'} |")
    lines.append("")
    (out / "report.md").write_text("\n".join(lines))
